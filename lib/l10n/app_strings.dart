  String _text(String key) {
    final languageCode =
        _values.containsKey(locale.languageCode) ? locale.languageCode : 'en';
    return _values[languageCode]?[key] ?? _values['en']![key] ?? key;
  }

  String text(String key) => _text(key);

  String languageLabel(String code) {
    switch (code) {
      case 'ms':
        return _text('languageMalay');
      case 'zh':
        return _text('languageChinese');
      default:
        return _text('languageEnglish');
    }
  }

  String genderLabel(String value) {
    switch (value.toLowerCase()) {
      case 'female':
        return _text('genderFemale');
      case 'other':
        return _text('genderOther');
      case 'male':
      default:
        return _text('genderMale');
    }
  }
